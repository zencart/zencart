<?php
/**
 * sync-agent-docs.php - copy the `.ai/` agent guidance into each tool's discovery location and
 * regenerate the index block in AGENTS.md.
 *
 * Source of truth (committed, hand-edited):
 *   .ai/rules/<name>.md          conventions for one area; frontmatter `paths:` lists globs
 *   .ai/skills/<name>/SKILL.md   Agent Skills format; frontmatter `name` + `description`
 *
 * Generated targets (committed, never hand-edited). Each is a stub: the frontmatter the tool
 * needs for discovery (`paths:` / `applyTo:` for rules, `name` + `description` for skills) plus
 * one line telling the agent to read the source file. No guide text is duplicated.
 *   .claude/rules/<name>.md                        Claude Code: `paths:` honored natively
 *   .github/instructions/<name>.instructions.md    GitHub Copilot: `applyTo:` frontmatter
 *   .claude/skills/<name>/SKILL.md                 Claude Code and Copilot
 *   .agents/skills/<name>/SKILL.md                 Codex and Copilot (Agent Skills standard location)
 *   AGENTS.md  between <!-- ai-index:start --> and <!-- ai-index:end -->   every tool
 *
 * Stubs rather than symlinks so Windows checkouts work (a symlink becomes a one-line text
 * file there and would load silently as the whole rule). Each stub carries a marker comment so
 * this script can prune targets whose source was removed without touching hand-made files.
 *
 * Zen Cart lives in the webroot, so every listable agent directory also gets the repo's blank
 * index.html and a deny-all .htaccess (same as logs/ and cache/). Tools ignore both: Claude
 * Code discovers only *.md rules and SKILL.md skills, Codex and Copilot only SKILL.md.
 *
 * Usage:
 *   php not_for_release/dev_tools/sync-agent-docs.php          write targets
 *   php not_for_release/dev_tools/sync-agent-docs.php --check  report differences, exit 1 if any (CI)
 *   composer docs-sync
 */

declare(strict_types=1);

$check = in_array('--check', $argv, true);
$root = realpath(__DIR__ . '/../..');
if ($root === false) {
    fwrite(STDERR, "Cannot resolve repo root\n");
    exit(2);
}
chdir($root);

const MARKER = 'Generated by not_for_release/dev_tools/sync-agent-docs.php from';
const INDEX_START = '<!-- ai-index:start -->';
const INDEX_END = '<!-- ai-index:end -->';

/** @return array{front: array<string, mixed>, body: string} */
function parseFrontmatter(string $src): array
{
    if (!preg_match('/^---\r?\n(.*?)\r?\n---\r?\n?(.*)$/s', $src, $m)) {
        return ['front' => [], 'body' => $src];
    }
    $front = [];
    $key = null;
    foreach (preg_split('/\r?\n/', $m[1]) as $line) {
        if (preg_match('/^([A-Za-z_-]+):\s*(.*)$/', $line, $km)) {
            $key = $km[1];
            $val = trim($km[2]);
            if ($val === '') {
                $front[$key] = [];
            } elseif (preg_match('/^\[(.*)\]$/', $val, $lm)) {
                $front[$key] = array_map(fn ($v) => trim($v, " \t\"'"), array_filter(array_map('trim', explode(',', $lm[1])), 'strlen'));
            } else {
                $front[$key] = trim($val, "\"'");
            }
        } elseif ($key !== null && preg_match('/^\s+-\s*(.+)$/', $line, $im)) {
            if (!is_array($front[$key])) {
                $front[$key] = [];
            }
            $front[$key][] = trim($im[1], " \t\"'");
        }
    }
    return ['front' => $front, 'body' => $m[2]];
}

/** @var array<string, string> $want  target path => content */
$want = [];
$rules = [];
$skills = [];

foreach (glob('.ai/rules/*.md') ?: [] as $file) {
    $name = basename($file, '.md');
    if ($name === 'index') {
        continue;
    }
    $src = (string)file_get_contents($file);
    ['front' => $front, 'body' => $body] = parseFrontmatter($src);
    $paths = (array)($front['paths'] ?? []);
    if ($paths === []) {
        fwrite(STDERR, "$file: missing `paths:` frontmatter\n");
        exit(2);
    }
    $title = preg_match('/^#\s+(.+)$/m', $body, $tm) ? trim($tm[1]) : $name;
    $rules[$name] = ['paths' => $paths, 'title' => $title, 'file' => $file];
    $note = "<!-- " . MARKER . " $file. Edit the source, then run: composer docs-sync -->\n";
    $stub = $note . "# {$title}\n\nRead `$file` and follow it. It applies to: " . implode(', ', array_map(fn ($p) => "`$p`", $paths)) . ".\n";
    $want[".claude/rules/$name.md"] = "---\npaths:\n" . implode('', array_map(fn ($p) => "  - \"$p\"\n", $paths)) . "---\n" . $stub;
    $want[".github/instructions/$name.instructions.md"] = "---\napplyTo: \"" . implode(', ', $paths) . "\"\n---\n" . $stub;
}

foreach (glob('.ai/skills/*/SKILL.md') ?: [] as $file) {
    $dir = dirname($file);
    $name = basename($dir);
    $src = (string)file_get_contents($file);
    ['front' => $front, 'body' => $body] = parseFrontmatter($src);
    if (($front['name'] ?? '') !== $name) {
        fwrite(STDERR, "$file: frontmatter `name` must equal the directory name ($name)\n");
        exit(2);
    }
    if (empty($front['description'])) {
        fwrite(STDERR, "$file: missing `description`\n");
        exit(2);
    }
    $skills[$name] = ['description' => $front['description'], 'file' => $file];
    $note = "<!-- " . MARKER . " $file. Edit the source, then run: composer docs-sync -->\n";
    $frontRaw = preg_match('/^(---\r?\n.*?\r?\n---\r?\n)/s', $src, $fm) ? $fm[1] : '';
    $title = preg_match('/^#\s+(.+)$/m', $body, $tm) ? trim($tm[1]) : $name;
    $stub = $frontRaw . $note . "# {$title}\n\nRead `$file` and follow it. Any supporting files it references live in `$dir/`.\n";
    foreach ([".claude/skills/$name", ".agents/skills/$name"] as $target) {
        $want["$target/SKILL.md"] = $stub;
    }
}

// ---- index block for AGENTS.md ---------------------------------------------------------------
$index = INDEX_START . "\n";
$index .= "Topic guides and skills live under `.ai/` (see `.ai/README.md`). Tools that auto-load path-scoped rules (Claude Code from `.claude/rules/`, Copilot from `.github/instructions/`) or skills (Claude Code, Copilot, Codex) receive these automatically. If yours does not, or the task does not touch a listed path, read the file yourself before planning or editing.\n\n";
$index .= "| Read when working on | Guide |\n|---|---|\n";
foreach ($rules as $name => $r) {
    $index .= '| ' . implode(', ', array_map(fn ($p) => "`$p`", $r['paths'])) . " | `{$r['file']}` ({$r['title']}) |\n";
}
$index .= "\n| Skill | Use when | File |\n|---|---|---|\n";
foreach ($skills as $name => $s) {
    // The full description is for the tools' own skill listings; the index only needs the trigger sentence.
    $when = preg_match('/\bUse (?:when|for|it|this)\b.*$/s', $s['description'], $wm) ? $wm[0] : $s['description'];
    $index .= "| `$name` | " . str_replace('|', '\\|', $when) . " | `{$s['file']}` |\n";
}
$index .= INDEX_END;

// ---- web-exposure guards: Zen Cart sits in the webroot ----------------------------------------
$blankIndex = is_file('zc_plugins/index.html') ? (string)file_get_contents('zc_plugins/index.html') : "<!DOCTYPE html>\n<html><head><title></title></head><body></body></html>\n";
$denyAll = <<<'HTACCESS'
#
# Generated by not_for_release/dev_tools/sync-agent-docs.php - deny all web access to agent guidance files.
# Same intent as logs/.htaccess: nothing in this directory tree is meant to be served.
#
<FilesMatch ".*">
  <IfModule mod_authz_core.c>
    Require all denied
  </IfModule>
  <IfModule !mod_authz_core.c>
    Order Allow,Deny
    Deny from all
  </IfModule>
</FilesMatch>

IndexIgnore */*

HTACCESS;
foreach (['.ai', '.ai/rules', '.ai/skills', '.agents', '.agents/skills', '.claude', '.claude/rules', '.claude/skills'] as $guardDir) {
    $want["$guardDir/index.html"] = $blankIndex;
    if (!str_contains($guardDir, '/')) {
        $want["$guardDir/.htaccess"] = $denyAll; // applies recursively; one per top-level dir
    }
}

$agents = (string)file_get_contents('AGENTS.md');
$start = strpos($agents, INDEX_START);
$end = strpos($agents, INDEX_END);
if ($start === false || $end === false || $end < $start) {
    fwrite(STDERR, "AGENTS.md: missing " . INDEX_START . " / " . INDEX_END . " markers\n");
    exit(2);
}
$want['AGENTS.md'] = substr($agents, 0, $start) . $index . substr($agents, $end + strlen(INDEX_END));

// ---- prune generated targets whose source is gone --------------------------------------------
$prune = [];
foreach (array_merge(glob('.claude/rules/*.md') ?: [], glob('.github/instructions/*.md') ?: [], glob('.claude/skills/*/SKILL.md') ?: [], glob('.agents/skills/*/SKILL.md') ?: []) as $existing) {
    if (isset($want[$existing])) {
        continue;
    }
    $head = (string)file_get_contents($existing, false, null, 0, 2000);
    if (str_contains($head, MARKER)) {
        $prune[] = $existing;
    }
}

// ---- apply or report --------------------------------------------------------------------------
$changed = [];
foreach ($want as $path => $content) {
    if (!is_file($path) || file_get_contents($path) !== $content) {
        $changed[] = $path;
        if (!$check) {
            if (!is_dir(dirname($path))) {
                mkdir(dirname($path), 0755, true);
            }
            file_put_contents($path, $content);
        }
    }
}
foreach ($prune as $path) {
    $changed[] = "$path (stale, source removed)";
    if (!$check) {
        unlink($path);
        $dir = dirname($path);
        if (basename($dir) !== 'rules' && basename($dir) !== 'instructions' && count(scandir($dir) ?: []) === 2) {
            rmdir($dir);
        }
    }
}

printf("%d rule(s), %d skill(s); %d target file(s).\n", count($rules), count($skills), count($want));
if ($changed === []) {
    echo "All targets up to date.\n";
    exit(0);
}
echo ($check ? "Out of date (run: composer docs-sync):\n" : "Written:\n");
foreach ($changed as $c) {
    echo "  $c\n";
}
exit($check ? 1 : 0);
